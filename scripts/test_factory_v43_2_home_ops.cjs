'use strict';
const fs=require('fs'), path=require('path'),assert=require('assert'),vm=require('vm'),crypto=require('crypto');
const root=path.resolve(__dirname,'..');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const web='services/edge-daemon/internal/web/static/';
const h=read(web+'portal.html'),css=read(web+'portal.css'),js=read(web+'portal.js');
assert(h.includes('ONE FACTORY. ONE CLEAR WORKFLOW.'));
assert(h.includes('Every garment<br><em>tells a story.</em>'));
assert(h.includes('id="why-agiparel"'));
assert.strictEqual((h.match(/agiparel-wave-canvas/g)||[]).length,1);
const whySection=h.match(/<section class="factory-why"[^>]*>([\s\S]*?)<\/section>/);
assert(whySection, 'Why Agiparel section must exist');
assert(whySection[1].includes('class="fabric-wave-art"'), 'wave must be inside the Why Agiparel section');
assert(whySection[1].indexOf('class="fabric-wave-art"')<whySection[1].indexOf('id="why-agiparel"'), 'wave must be behind details, not below it');
assert(!h.slice(h.indexOf('</section>',h.indexOf('<section class="factory-why"')),h.indexOf('</main>')).includes('class="fabric-wave-art"'), 'no separate bottom wave panel');
assert(h.includes('aria-hidden="true"'));
assert(!h.includes('One connected factory.'));
assert(!h.includes('FROM FIRST THREAD TO FINAL CARTON'));
const legacyVisibleCopy=h.replace(/<nav class="site-links"[^>]*>[\s\S]*?<\/nav>/,'').replace(/<!--[\s\S]*?-->/g,'').replace(/<[^>]+>/g,' ').replace(/\s+/g,' ').trim();
assert.strictEqual(crypto.createHash('sha256').update(legacyVisibleCopy).digest('hex'), 'cc7ee683b8e1b54c9d908d6bc041cf11367d50505400eea9ec2e25ccf3cbe123', 'original home page wording must remain byte-equivalent, excluding requested new account navigation');
assert(css.includes('position:absolute;inset:0') && css.includes('background:rgba(255,255,255,.68)'), 'waves must be behind translucent Why details');
assert(css.includes('.fabric-wave-art') && css.includes('--accent:#167e88'));
assert(js.includes('prefers-reduced-motion')&&js.includes('IntersectionObserver'));
assert(js.includes("canvas.closest('.fabric-wave-art')"));
const ops=read(web+'engineer_ops.html'), ojs=read(web+'engineer_ops.js');
assert(ops.includes('<details class="inventory ops-details" id="db-catalog"'));
assert(ops.includes('<details class="inventory ops-details" id="api-catalog"'));
for(const id of ['customer-count','user-count','usage-count','api-filter','api-rows','catalog']) assert(ops.includes('id="'+id+'"'));
assert(ojs.includes('textContent')&&ojs.includes("fetch('/api/v1/engineer-ops/overview'"));
assert(!ojs.includes('innerHTML'));
const routes=read('services/edge-daemon/cmd/server/engineer_ops_api_catalog_v43_2.go');
const matches=[...routes.matchAll(/^\s*"(\/api\/[^"]+)",/gm)];
assert(matches.length>=160, 'API catalog must include all actual registered APIs');
assert(routes.includes('/api/v1/packing/dock/verification'));
const go=read('services/edge-daemon/cmd/server/engineer_ops_v43.go');
assert(go.includes('engineerOpsRequestsSinceStart')&&go.includes('engineer_ops_counts_v43_2()'));
assert(go.includes('RequestsSinceStart')&&go.includes('SourceStatus'));
console.log('PASS v43.2.1: original copy unchanged, fabric waves behind Why Agiparel, Engineer Ops unchanged');
